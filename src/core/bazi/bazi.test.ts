const MINUTE = 60_000;

function chart(date: string, time: string, utcOffsetMinutes = 480): BaziChart {
  return computeChart({ date, time, utcOffsetMinutes });
}

function names(c: BaziChart): string {
  const { year, month, day, hour } = c.pillars;
  return [year.name, month.name, day.name, hour.name].join(" ");
}

